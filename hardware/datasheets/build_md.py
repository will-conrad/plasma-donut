#!/usr/bin/env python3
"""Make <part>.md next to every <part>.pdf in this folder.

Each .md holds a header from manifest.json (name, role, reference
designators, source, revision, pages, SHA-256), a link to the part card in
docs/parts/ if there is one, and then the full text of every page under a
"## Page N" heading. "p.N" in a citation such as (mcp3208 p.3) is page N of
the PDF, which is "## Page N" in the .md.

Usage (from anywhere):
    python3 hardware/datasheets/build_md.py            # every PDF
    python3 hardware/datasheets/build_md.py mcp3208    # one part
    python3 hardware/datasheets/build_md.py --check    # verify hashes only

Needs pdftotext and pdfinfo from poppler (macOS: brew install poppler).
A PDF that isn't in manifest.json yet is added to it with its hash and
page count; fill in the other fields by hand afterwards.
"""
import datetime
import hashlib
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
MANIFEST = os.path.join(HERE, "manifest.json")
CARDS = os.path.join(REPO, "docs", "parts")


def sha256(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def page_count(pdf):
    out = subprocess.run(["pdfinfo", pdf], capture_output=True, text=True, check=True).stdout
    return int(re.search(r"^Pages:\s+(\d+)", out, re.M).group(1))


def page_text(pdf, n):
    out = subprocess.run(
        ["pdftotext", "-layout", "-enc", "UTF-8", "-f", str(n), "-l", str(n), pdf, "-"],
        capture_output=True, text=True, check=True,
    ).stdout
    out = out.replace("\f", "").rstrip()
    # Drop trailing spaces; keep the column layout, since tables depend on it.
    return "\n".join(line.rstrip() for line in out.splitlines())


def header(key, p):
    rows = [
        ("Part", p.get("name", key)),
        ("Manufacturer", p.get("manufacturer", "")),
        ("Role on the board", p.get("role", "")),
        ("Reference designators", p.get("refs", "")),
        ("Source", p.get("source_url", "")),
        ("Mirror", p.get("mirror_url", "")),
        ("Revision", p.get("revision", "")),
        ("Retrieved", p.get("retrieved", "")),
        ("Pages", str(p.get("pages", ""))),
        ("SHA-256", f"`{p['sha256']}`" if p.get("sha256") else ""),
    ]
    lines = [f"# {p.get('name', key)}", "",
             f"Full text of [`{key}.pdf`]({key}.pdf), page by page. Generated by `build_md.py`; "
             "don't edit by hand, re-run the script instead.", "",
             "| Field | Value |", "|---|---|"]
    lines += [f"| {a} | {b} |" for a, b in rows if b]
    if os.path.exists(os.path.join(CARDS, key + ".md")):
        lines += ["", f"**Board notes** (how this part is used, gotchas, key specs with pages): "
                      f"[docs/parts/{key}.md](../../docs/parts/{key}.md)"]
    lines += ["", "**Extraction caveat:** text comes from `pdftotext -layout`. Graphs and drawings "
                  "don't come through, and symbol fonts can garble units (e.g. \"mW\" for mΩ, "
                  "\"mA\" for µA). Check any number you rely on against the PDF page."]
    if p.get("note"):
        lines += ["", f"**Note:** {p['note']}"]
    return "\n".join(lines)


def build(key, manifest):
    pdf = os.path.join(HERE, key + ".pdf")
    p = manifest["parts"].setdefault(key, {"name": key})
    h = sha256(pdf)
    if p.get("sha256") and p["sha256"] != h:
        print(f"  {key}: PDF changed since the manifest was written (new revision?). Updating hash.")
        p["retrieved"] = datetime.date.today().isoformat()
    p.update(sha256=h, bytes=os.path.getsize(pdf), pages=page_count(pdf), pdf=key + ".pdf", md=key + ".md")
    if p.get("note", "").startswith("PDF not in the repo"):
        del p["note"]
    body = [header(key, p), ""]
    for n in range(1, p["pages"] + 1):
        body += ["", f"## Page {n}", "", "```text", page_text(pdf, n), "```"]
    with open(os.path.join(HERE, key + ".md"), "w", encoding="utf-8") as f:
        f.write("\n".join(body) + "\n")
    print(f"  {key}.md  ({p['pages']} pages)")


def placeholder(key, p):
    """An .md for a part whose PDF isn't here yet, so the folder still lists it."""
    with open(os.path.join(HERE, key + ".md"), "w", encoding="utf-8") as f:
        f.write(header(key, p) + "\n\n_No page text yet: the PDF is missing._\n")
    print(f"  {key}.md  (placeholder, PDF missing)")


def main(argv):
    with open(MANIFEST, encoding="utf-8") as f:
        manifest = json.load(f)
    pdfs = sorted(f[:-4] for f in os.listdir(HERE) if f.endswith(".pdf"))

    if "--check" in argv:
        bad = 0
        for key in pdfs:
            want = manifest["parts"].get(key, {}).get("sha256")
            ok = want == sha256(os.path.join(HERE, key + ".pdf"))
            bad += not ok
            print(f"  {'ok ' if ok else 'BAD'} {key}")
        return 1 if bad else 0

    keys = [a for a in argv if not a.startswith("-")] or pdfs
    for key in keys:
        if key in pdfs:
            build(key, manifest)
        elif key in manifest["parts"]:
            placeholder(key, manifest["parts"][key])
        else:
            print(f"  {key}: no {key}.pdf here and not in manifest.json")
    if not argv:  # full run: also refresh placeholders for parts with no PDF
        for key, p in manifest["parts"].items():
            if key not in pdfs:
                placeholder(key, p)

    manifest["updated"] = datetime.date.today().isoformat()
    with open(MANIFEST, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2, ensure_ascii=False)
        f.write("\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
