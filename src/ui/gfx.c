void gfx_clear(void)            { memset(gfx_fb, 0x00, sizeof gfx_fb); }
void gfx_fill(uint8_t pattern)  { memset(gfx_fb, pattern, sizeof gfx_fb); }

void gfx_pixel(int x, int y, bool on)
{
    if (x < 0 || x >= GFX_W || y < 0 || y >= GFX_H_PX) return;
    uint8_t bit = (uint8_t)(1u << (y & 7));
    if (on) gfx_fb[y >> 3][x] |= bit;
    else    gfx_fb[y >> 3][x] &= (uint8_t)~bit;
}

bool gfx_get(int x, int y)
{
    if (x < 0 || x >= GFX_W || y < 0 || y >= GFX_H_PX) return false;
    return (gfx_fb[y >> 3][x] >> (y & 7)) & 1u;
}

void gfx_hline(int x0, int x1, int y) { for (int x = x0; x <= x1; x++) gfx_pixel(x, y, true); }
void gfx_vline(int x, int y0, int y1) { for (int y = y0; y <= y1; y++) gfx_pixel(x, y, true); }

void gfx_rect(int x0, int y0, int x1, int y1)
{
    gfx_hline(x0, x1, y0); gfx_hline(x0, x1, y1);
    gfx_vline(x0, y0, y1); gfx_vline(x1, y0, y1);
}

int gfx_text(int x, int line, const char *s)
{
    if (line < 0 || line >= GFX_PAGES) return x;
    for (; *s; s++) {
        unsigned char c = (unsigned char)*s;
        if (c < 0x20 || c > 0x7E) c = '?';
        for (int i = 0; i < 5; i++) {
            if (x + i >= 0 && x + i < GFX_W) gfx_fb[line][x + i] = font5x7[c - 0x20][i];
        }
        if (x + 5 >= 0 && x + 5 < GFX_W) gfx_fb[line][x + 5] = 0x00;
        x += GFX_CHAR_W;
    }
    return x;
}

void gfx_invert_line(int line)
{
    if (line < 0 || line >= GFX_PAGES) return;
    for (int x = 0; x < GFX_W; x++) gfx_fb[line][x] ^= 0xFF;
}
